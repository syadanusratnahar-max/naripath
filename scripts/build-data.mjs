// Regenerates db/resources.json, db/allowances.json and the numbers in README.md
// from the data inside index.html, so every count comes from one place.
// Usage: node scripts/build-data.mjs        (no dependencies)
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";

const html = readFileSync("index.html", "utf8");
const script = html.slice(html.indexOf("<script>") + 8, html.indexOf("</script>", html.indexOf("<script>")));
const between = (start, end, from = 0) => {
  const a = script.indexOf(start, from);
  if (a < 0) throw new Error("Not found: " + start);
  const b = script.indexOf(end, a);
  if (b < 0) throw new Error("No end for: " + start);
  return script.slice(a, b + end.length);
};
const line = start => between(start, "\n");

const code = [
  between("/* ---------------- Reference data", "return m; },{});"),
  line("const K = "),
  between("const GSRC = {", "\n};"),
  between("Object.assign(GSRC, {", "\n});"),
  line("const TOOL_CHECKED="), line("const DSS_APPLY="),
  between("Object.assign(GSRC,{", "\n});", script.indexOf("const DSS_APPLY=")),
  between("const ALLOW=[", "\n];"),
  "globalThis.OUT = {R, ALLOW, GSRC, DISTRICTS, TOTAL_DISTRICTS, PILLARS, TOOL_CHECKED};"
].join("\n");

const ctx = { S: { lang: "en" } };
vm.createContext(ctx);
vm.runInContext(code, ctx);
const { R, ALLOW, GSRC, DISTRICTS, TOTAL_DISTRICTS, TOOL_CHECKED } = ctx.OUT;

const PK = { 1: "education-career", 2: "health-wellbeing", 3: "rights-legal", 4: "personal-digital-safety", 5: "financial-independence", 6: "everyday-community" };
const ST = { review: "needs_review", awaiting: "awaiting_confirmation", confirmed: "provider_confirmed", demo: "demo" };
const t = o => o || { en: null, bn: null };
const resources = R.map(r => ({
  id: r.id, pillar: PK[r.p], data_type: r.type === "demo" ? "B_demo" : "A_public_source",
  status: ST[r.status] || (r.type === "demo" ? "demo" : "public_source"), not_found: r.notFound,
  location: r.loc, cost: r.cost, life_stages: r.stages,
  name_en: r.name.en, name_bn: r.name.bn, org_en: t(r.org).en, org_bn: t(r.org).bn,
  description_en: t(r.desc).en, description_bn: t(r.desc).bn,
  eligibility_en: t(r.elig).en, eligibility_bn: t(r.elig).bn,
  required_documents: r.docs, phone: r.phone || null, email: r.email || null, website: r.web || null, facebook: r.fb || null,
  address_en: t(r.address).en, address_bn: t(r.address).bn, caution_en: t(r.note).en, caution_bn: t(r.note).bn,
  sources: r.source.map(s => ({ en: s.en, bn: s.bn, url: s.url })), last_checked: r.checked, next_review: r.next
}));
const allowances = ALLOW.map(a => ({
  id: a.id, name: a.name, amount: a.amount, office: a.office, final_confirmation: a.office, about: a.about, when: a.when,
  apply_url: a.apply, documents: a.docs, still_to_confirm: a.confirm, warning: a.warn || null,
  sources: a.sources.map(k => GSRC[k]).map(s => ({ en: s.en, bn: s.bn, url: s.url })), last_checked: a.checked || TOOL_CHECKED
}));
writeFileSync("db/resources.json", JSON.stringify(resources, null, 2) + "\n");
writeFileSync("db/allowances.json", JSON.stringify(allowances, null, 2) + "\n");

const local = new Set(R.filter(r => r.loc !== "nationwide").map(r => r.loc));
const checked = R.map(r => r.checked).filter(Boolean).sort();
const fmt = d => new Date(d + "T00:00:00Z").toLocaleDateString("en-GB", { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
const stats = `<!-- stats:start (generated by scripts/build-data.mjs; do not edit by hand) -->
- **${R.length}** public-source records, checked between ${fmt(checked[0])} and ${fmt(checked.at(-1))}
- **${local.size} of ${TOTAL_DISTRICTS}** districts have at least one local listing (${[...local].map(k => DISTRICTS[k].en).join(", ")}); other districts rely on nationwide services
- **${ALLOW.length}** government allowances (FY2026-27), last checked ${fmt(TOOL_CHECKED)}
<!-- stats:end -->`;
let readme = readFileSync("README.md", "utf8");
readme = readme.replace(/<!-- stats:start[\s\S]*?<!-- stats:end -->/, stats);
writeFileSync("README.md", readme);
console.log(stats);
